#!/usr/bin/env python3
"""Argon-4 Consultation: Comprehensive CIO Evaluation & Cross-Tower Value Audit of Consolidated AS-IS Deliverables.

Analyzes:
1. Tomo 1: Diagnóstico AS-IS Consolidado (CTO/CIO Transversal).
2. Informe Maestro CIO Consolidado.

Evaluates:
- What score (0-100 / 0-10) a top-tier CIO would assign to this document.
- Does it capture the FULL value of all analyzed capability towers (T1-T10)?
- Concrete gaps, blind spots, and human-centric executive observations.
"""

from __future__ import annotations

import sys
from pathlib import Path
from docx import Document

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from assessment_engine.infrastructure.genai_client import (
    ModelTier,
    create_genai_client,
    get_model,
)


def extract_docx_summary(file_path: Path) -> str:
    doc = Document(file_path)
    lines = []
    lines.append(f"=== DOCUMENT: {file_path.name} ===")
    for p in doc.paragraphs:
        txt = p.text.strip()
        if txt:
            lines.append(f"[{p.style.name}]: {txt}")
    for idx, tbl in enumerate(doc.tables):
        lines.append(f"\n--- TABLE {idx} ({len(tbl.rows)} rows, {len(tbl.columns)} cols) ---")
        for r_idx, row in enumerate(tbl.rows):
            row_txt = " | ".join(c.text.replace("\n", " ").strip() for c in row.cells)
            lines.append(f"Row {r_idx}: {row_txt[:160]}")
    return "\n".join(lines)


def main() -> None:
    client = create_genai_client()
    model_name = get_model(ModelTier.REASONING)

    f1 = REPO_ROOT / "working/out/Molins_Entrega_Oficial_Piramide_Tier1/01_TRIADA_ESTRATEGICA_TRANSVERSAL_CTO/Molins_202610_Tomo_1_Diagnostico_ASIS.docx"
    f2 = REPO_ROOT / "working/out/Molins_Entrega_Oficial_Piramide_Tier1/00_INFORME_MAESTRO_CIO/Molins_202610_Informe_Consolidado.docx"

    tomo1_text = extract_docx_summary(f1)
    informe_text = extract_docx_summary(f2)

    prompt = f"""
Role: You are an elite Fortune 500 / IBEX-35 Chief Information Officer (CIO) and Senior Partner at Gartner Executive Programs.

MANDATE FROM THE USER:
"lo que quiero es que con gemini-4-argon y luego revisándolo como lo ve un humano hagas una revisión del as is consolidado y me des tu diagnóstico si lo lee el CIO y qué puntuación nos da y si en el documento contamos todo el valor de las torres analizadas"

CONTEXT & DOCUMENTATION:
Below is the exact extracted content of the consolidated AS-IS deliverables for Molins:
1. Tomo 1: Diagnóstico AS-IS Consolidado (transversal document for CTO/CIO).
2. Informe Maestro CIO Consolidado (Board memo & C-suite strategic report).

--- START OF TOMO 1: DIAGNÓSTICO AS-IS CONSOLIDADO ---
{tomo1_text}
--- END OF TOMO 1 ---

--- START OF INFORME MAESTRO CIO ---
{informe_text}
--- END OF INFORME MAESTRO CIO ---

YOUR TASK:
Provide an authoritative, rigorous, and frank evaluation report structured in Spanish with:

1. CIO EXECUTIVE VERDICT & SCORE (0 to 10 and 0 to 100):
   - What exact grade does the CIO give this deliverable?
   - What is the CIO's honest first impression when opening this document?
   - Does it justify an immediate Board decision, or does it leave unanswered questions?

2. CAPTURE OF VALUE ACROSS ALL EVALUATED TOWERS (T1 TO T10):
   - Are we really telling the FULL story and capturing all the value of the 10 capability towers?
   - Compare the depth of the individual technical annexes (e.g. T1 Data Center and T2 Compute, which each have ~16 pages of rich FAIR risk derivations, telemetry, 5x5 heatmaps, and CMMI evaluations) against what is summarized here in Tomo 1 and the Master Report.
   - Is Table 7 in Tomo 1 (which only gives a 1-sentence diagnostic per tower) sufficient for a CIO, or is it an over-compression that hides 90% of the engineering value generated by the audit?
   - What specific domain insights from T1, T2, T3 (Networks), T4 (Storage), T5 (Industrial/IoT), T6 (Cybersecurity/Identity), T7 (Database), T8 (Applications/SAP), T9 (Digital Workplace), and T10 (Observability/ITSM) are MISSING from the consolidated AS-IS?

3. HUMAN-CENTRIC & EDITORIAL CRITIQUE (How a human reader perceives it):
   - Is the document balanced, visually compelling, and proportioned?
   - Does the Table of Contents promise sections (e.g., Chapter 3 O-FAIR risk quantification, Chapter 4 SPOF matrix, Chapter 5 Interdependencies) that are barely fleshed out in the actual text (notice Tomo 1 only has 526 words total)?
   - What is the cognitive friction for a human executive reading this?

4. CONCRETE, ACTIONABLE ROADMAP TO REACH A 10/10 SCORE:
   - Specific enhancements needed to make the Consolidated AS-IS document an undeniable masterpiece that justifies millions in budget allocation.
"""

    print(f"Requesting adversarial CIO review from {model_name}...")
    response = client.models.generate_content(
        model=model_name,
        contents=prompt,
    )

    out_file = REPO_ROOT / "docs/architecture/CIO_ADVERSARIAL_REVIEW_CONSOLIDATED_ASIS_ARGON.md"
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(response.text, encoding="utf-8")

    print("\n" + "=" * 80)
    print("GEMINI-4-ARGON: CIO EVALUATION REPORT ON CONSOLIDATED AS-IS")
    print("=" * 80)
    print(response.text)
    print("=" * 80)
    print(f"\nReport saved to: {out_file.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
