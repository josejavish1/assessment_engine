"""
Cryptographic Provenance Enveloper for Zero-Hallucination Integrity.
Implements Phase 2 of ARGON_GLOBAL_TIER1_MASTER_PLAN.md.

Mandates:
1. Strict differentiation between EMPIRICAL_VERIFIED (stated by client/telemetry) and ACTUARIALLY_DERIVED (Bayesian models).
2. Permanent prohibition of unverified speculative inferences (e.g. fabricated patch levels or synthetic ratios).
3. SHA-256 cryptographic provenance hashing for audit traceability.
"""

from __future__ import annotations

import hashlib
import json
from enum import StrEnum
from typing import Any, Optional
from pydantic import BaseModel, ConfigDict, Field


class ProvenanceClassification(StrEnum):
    """Authoritative epistemic status of an ingested data point or metric."""

    EMPIRICAL_VERIFIED = "EMPIRICAL_VERIFIED"
    ACTUARIALLY_DERIVED = "ACTUARIALLY_DERIVED"


class EnvelopedMetric(BaseModel):
    """Immutable data envelope guaranteeing epistemic provenance and mathematical confidence."""

    model_config = ConfigDict(
        frozen=True,
        extra="forbid",
        strict=True,
    )

    metric_name: str = Field(..., description="Canonical metric identifier")
    value: Any = Field(..., description="Observed or simulated metric value")
    classification: ProvenanceClassification = Field(..., description="Epistemic verification status")
    source_citation: str = Field(..., description="Document transcript, telemetry tool, or prior distribution citation")
    mathematical_confidence: float = Field(
        ..., ge=0.0, le=1.0, description="1.0 for verified facts; Bayesian confidence score for derived values"
    )
    provenance_hash: str = Field(..., description="Cryptographic SHA-256 audit fingerprint")


class ProvenanceEnveloper:
    """Factory and validator for cryptographically enveloped metrics."""

    @staticmethod
    def _compute_hash(metric_name: str, value: Any, classification: str, source: str) -> str:
        payload = f"{metric_name}:{value}:{classification}:{source}"
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    @classmethod
    def wrap_empirical_fact(cls, metric_name: str, value: Any, source_citation: str) -> EnvelopedMetric:
        """Wrap a verified empirical observation directly confirmed by client interview or telemetry export."""
        h = cls._compute_hash(metric_name, value, ProvenanceClassification.EMPIRICAL_VERIFIED.value, source_citation)
        return EnvelopedMetric(
            metric_name=metric_name,
            value=value,
            classification=ProvenanceClassification.EMPIRICAL_VERIFIED,
            source_citation=source_citation,
            mathematical_confidence=1.0,
            provenance_hash=h,
        )

    @classmethod
    def wrap_actuarial_estimate(
        cls, metric_name: str, value: Any, model_citation: str, confidence: float = 0.90
    ) -> EnvelopedMetric:
        """Wrap an actuarially estimated metric generated by Bayesian conjugation or Monte Carlo simulation."""
        h = cls._compute_hash(metric_name, value, ProvenanceClassification.ACTUARIALLY_DERIVED.value, model_citation)
        return EnvelopedMetric(
            metric_name=metric_name,
            value=value,
            classification=ProvenanceClassification.ACTUARIALLY_DERIVED,
            source_citation=model_citation,
            mathematical_confidence=confidence,
            provenance_hash=h,
        )
