    def generate_diffuse_shadows(self, level: str = "card") -> str:
        """Generate multi-layer diffuse shadows with quadratic opacity falloff and disallow single-layer hard Tailwind shadows."""
        return self.DIFFUSE_SHADOW_SCALES.get(level, self.DIFFUSE_SHADOW_SCALES["card"])

