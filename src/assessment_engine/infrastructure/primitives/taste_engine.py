"""
Provide the core craft and micro-interactions primitive (RFC-016 / RFC-017). Formally encode design principles from Emil Kowalski (Linear/Sonner) and Impeccable's 59 anti-AI-slop rules:
1. Deterministic multi-layer diffuse shadow generator (4 layers with quadratic falloff).
2. Translucent micro-border injector with top inset lighting.
3. Deterministic aesthetic anti-pattern linter for TSX/JSX code.
4. Syntactic auto-remediation engine for design violations.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class TasteViolation:
    """Represent a visual design or micro-interaction violation in code."""
    rule_id: str
    severity: str  # ERROR | WARNING
    description: str
    matched_snippet: str
    remediation: str


@dataclass
class TasteAuditReport:
    """Represent a forensic report generated by the TasteEngine aesthetic linter."""
    passed: bool
    score: float
    violations: list[TasteViolation] = field(default_factory=list)
    repaired_code: str | None = None


