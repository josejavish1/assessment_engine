        """Resolve a high-resolution, uncompressed Unsplash photo URL for the given sector."""
        clean_sector = sector.lower().strip().replace("-", "_").replace(" ", "_")
        photo_id = self.CURATED_HERO_ASSETS.get(clean_sector, self.CURATED_HERO_ASSETS["default"])
        prefix = "" if photo_id.startswith("photo-") else "photo-"
        return f"https://images.unsplash.com/{prefix}{photo_id}?auto=format&fit=crop&w={width}&q={quality}"

