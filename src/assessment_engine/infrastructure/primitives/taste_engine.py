    def _check_transition_all(self, tsx_code: str) -> list[TasteViolation]:
        """Detect indiscriminate use of transition-all."""
        violations: list[TasteViolation] = []
        if re.search(r"\btransition-all\b", tsx_code):
            for match in re.finditer(r"[^\n]*\btransition-all\b[^\n]*", tsx_code):
                violations.append(
                    TasteViolation(
                        rule_id="TASTE-NO-TRANSITION-ALL",
                        severity="ERROR",
                        description="Prohibido 'transition-all'. Declara propiedades explícitas para evitar jank.",
                        matched_snippet=match.group(0).strip(),
                        remediation="transition-[transform,opacity] duration-150 ease-out",
                    )
                )
        return violations

    def _check_harsh_shadows(self, tsx_code: str) -> list[TasteViolation]:
        """Detect single-layer hard Tailwind shadows."""
        violations: list[TasteViolation] = []
        if re.search(r"\bshadow-(?:md|lg|xl|2xl)\b", tsx_code):
            for match in re.finditer(r"[^\n]*\bshadow-(?:md|lg|xl|2xl)\b[^\n]*", tsx_code):
                violations.append(
                    TasteViolation(
                        rule_id="TASTE-NO-HARSH-SHADOWS",
                        severity="ERROR",
                        description="Sombras duras de Tailwind detectadas. Usa sombras difusas multicapa.",
                        matched_snippet=match.group(0).strip(),
                        remediation=f"shadow-[{self.generate_diffuse_shadows('card')}]",
                    )
                )
        return violations

    def _check_button_active_scale(self, tsx_code: str) -> list[TasteViolation]:
        """Detect buttons missing active:scale elastic feedback."""
        violations: list[TasteViolation] = []
        button_matches = re.findall(r"<button\b[^>]*className=[\"']([^\"']*)[\"']", tsx_code)
        for cls in button_matches:
            if "active:scale-" not in cls and "active:scale" not in cls:
                violations.append(
                    TasteViolation(
                        rule_id="TASTE-BUTTON-NO-ACTIVE-SCALE",
                        severity="ERROR",
                        description="Botón sin micro-interacción táctil al pulsarlo.",
                        matched_snippet=cls[:60],
                        remediation="active:scale-[0.98] transition-transform duration-150 ease-out",
                    )
                )
        return violations

    def _check_scale_and_durations(self, tsx_code: str) -> list[TasteViolation]:
        """Detecta scale(0) y duraciones mayores a 250ms."""
        violations: list[TasteViolation] = []
        if "scale(0)" in tsx_code or "scale-0" in tsx_code:
            violations.append(
                TasteViolation(
                    rule_id="TASTE-NO-SCALE-ZERO",
                    severity="ERROR",
                    description="Prohibido animar desde scale(0). Los elementos deben entrar desde scale(0.95-0.98).",
                    matched_snippet="scale(0) / scale-0",
                    remediation="scale-[0.98] opacity-0",
                )
            )

        if re.search(r"\bduration-(?:300|500|700|1000)\b", tsx_code):
            for match in re.finditer(r"[^\n]*\bduration-(?:300|500|700|1000)\b[^\n]*", tsx_code):
                violations.append(
                    TasteViolation(
                        rule_id="TASTE-NO-SLOW-TRANSITIONS",
                        severity="WARNING",
                        description="Transición interactiva > 250ms hace lenta la UI percibida.",
                        matched_snippet=match.group(0).strip(),
                        remediation="duration-150 o duration-200",
                    )
                )
        return violations

    def audit_taste_contracts(self, tsx_code: str) -> TasteAuditReport:
        """
        Deterministically audit code against the 5 AI-slop anti-patterns.
        """
        violations: list[TasteViolation] = []
        violations.extend(self._check_transition_all(tsx_code))
        violations.extend(self._check_harsh_shadows(tsx_code))
        violations.extend(self._check_button_active_scale(tsx_code))
        violations.extend(self._check_scale_and_durations(tsx_code))

        err_count = len([v for v in violations if v.severity == "ERROR"])
        warn_count = len([v for v in violations if v.severity == "WARNING"])
        score = max(0.0, 20.0 - (err_count * 3.0) - (warn_count * 1.0))
        passed = err_count == 0

        return TasteAuditReport(
            passed=passed,
            score=score,
            violations=violations,
        )

    def auto_repair_taste_violations(self, tsx_code: str) -> str:
        """
        Deterministically auto-fix AI-slop violations in TSX code.
        """
        repaired = tsx_code

        # 1. Replace transition-all with explicit properties
        repaired = re.sub(
            r"\btransition-all\b",
            "transition-[transform,opacity,border-color]",
            repaired,
        )

        repaired = re.sub(
            r"\bshadow-(?:md|lg|xl|2xl)\b",
            "shadow-[0_2px_4px_rgba(0,0,0,0.02),0_12px_28px_rgba(0,0,0,0.04)]",
            repaired,
        )

        # 3. Inject active:scale-[0.98] into buttons lacking it
        def fix_button(match: re.Match[str]) -> str:
            """Replace the matched button pattern with the corrected string."""
            full = match.group(0)
            if "active:scale-" not in full:
                # Inject at the end of className
                return re.sub(
                    r"className=[\"']([^\"']*)[\"']",
                    r"className='\1 active:scale-[0.98] transition-transform duration-150 ease-out'",
                    full,
                )
            return full

        repaired = re.sub(r"<button\b[^>]*>", fix_button, repaired)

        repaired = re.sub(
            r"\bduration-(?:300|500|700)\b",
            "duration-150",
            repaired,
        )

        # 5. Corregir scale-0 a scale-[0.98]
        repaired = re.sub(
            r"\bscale-0\b",
            "scale-[0.98] opacity-0",
            repaired,
        )

        # 6. Corregir overlays translúcidos sobre variables hex a opacidad nativa
        repaired = re.sub(
            r'bg-surface-container(?:-lowest|-low)?/(?:50|60|70|80)',
            'bg-white/85 backdrop-blur-[2px]',
            repaired
        )

        return repaired


